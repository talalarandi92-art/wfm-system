export function searchKnowledge(query: string, limit = 4): KnowledgeTopic[] {
  const q = (query || '').toLowerCase();
  const terms = q.split(/\s+/).filter(t => t.length > 1);
  if (!terms.length) return KNOWLEDGE.slice(0, limit);
  const scored = KNOWLEDGE.map(k => {
    const hay = `${k.titleAr} ${k.titleEn} ${k.tags.join(' ')} ${k.body}`.toLowerCase();
    let score = 0;
    for (const t of terms) if (hay.includes(t)) score += hay.split(t).length - 1;
    for (const tag of k.tags) if (terms.includes(tag.toLowerCase())) score += 5;
    return { k, score };
  }).filter(x => x.score > 0).sort((a, b) => b.score - a.score);
  return (scored.length ? scored : KNOWLEDGE.map(k => ({ k, score: 0 }))).slice(0, limit).map(x => x.k);
}
