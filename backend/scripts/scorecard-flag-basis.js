#!/usr/bin/env node
/**
 * WHAT DOES "NEEDS COACHING" ACTUALLY MEAN? — a report on the low_scorecard trigger.
 *
 * `scorecard-guard.scan()` opens a coaching flag for every agent whose Net Points
 * are BELOW THEIR FUNCTION'S AVERAGE. That is not a performance threshold, it is
 * an arithmetic identity: in any group, roughly half the members are below the
 * group's mean, forever, no matter how well everyone is doing. A team could lift
 * every single score and the same proportion would still be flagged.
 *
 * Measured on the live database (February 2026, the only uploaded batch):
 *   73 scored agents · 31 flagged (42.5%) · 31 open low_scorecard rows right now.
 *
 * That is 31 real people carrying an open HR record generated by a rule that
 * cannot ever flag fewer. This platform's standing principle is that ambiguous
 * evidence goes to review, never to an HR action — a trigger that fires on 42% of
 * the workforce by construction does not clear that bar.
 *
 * THIS SCRIPT ONLY REPORTS. There is no --apply, deliberately: replacing the
 * trigger is a business-rule change (BR-APP-006 / D-000) and belongs to the
 * Director, not to a script and not to me. It models the alternatives side by side
 * so the choice can be made on numbers instead of intuition.
 *
 *   node scripts/scorecard-flag-basis.js
 */
const fs = require('fs'), path = require('path'), { Client } = require('pg');
for (const p of [path.join(__dirname, '..', '.env'), path.join(__dirname, '..', '..', '.env')])
  if (fs.existsSync(p)) for (const l of fs.readFileSync(p, 'utf8').split(/\r?\n/)) {
    const m = l.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }

const bold = (s) => `\x1b[1m${s}\x1b[0m`;
const dim = (s) => `\x1b[90m${s}\x1b[0m`;

(async () => {
  const c = new Client({ host: process.env.POSTGRES_HOST, port: +process.env.POSTGRES_PORT,
    database: process.env.POSTGRES_DB, user: process.env.POSTGRES_USER, password: process.env.POSTGRES_PASSWORD });
  await c.connect();
  const q = async (sql, p = []) => (await c.query(sql, p)).rows;

  const [batch] = await q(
    `SELECT id, period_name FROM scorecard_batches WHERE status <> 'archived'
      ORDER BY period_year DESC NULLS LAST, period_month DESC NULLS LAST, uploaded_at DESC LIMIT 1`);
  if (!batch) { console.log('No scorecard batch uploaded — nothing to report.'); await c.end(); return; }

  /* The official month result per agent, with their function's mean and spread. */
  /* PERCENTILE_CONT is an ordered-set aggregate — Postgres does not accept OVER on
     it — so the per-function quartile is computed in its own CTE and joined back. */
  const rows = await q(
    `WITH e AS (
       SELECT function_name fn, employee_no, employee_name nm, net_points pts
         FROM scorecard_entries
        WHERE batch_id = $1 AND week_label = 'Final' AND net_points IS NOT NULL
     ), agg AS (
       SELECT fn, AVG(pts) fn_avg, STDDEV_POP(pts) fn_sd,
              PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY pts) fn_p25
         FROM e GROUP BY fn
     )
     SELECT e.*, agg.fn_avg, agg.fn_sd, agg.fn_p25
       FROM e JOIN agg USING (fn)`, [batch.id]);

  const openFlags = await q(
    `SELECT COUNT(*)::int n FROM coaching_flags WHERE trigger_type = 'low_scorecard' AND status = 'open'`);

  const n = rows.length;
  const count = (fn) => rows.filter(fn).length;
  const pct = (k) => `${((k / n) * 100).toFixed(1)}%`;

  console.log(`\n${bold('LOW-SCORECARD COACHING TRIGGER — what it actually selects')}`);
  console.log(dim(`period ${batch.period_name} · ${n} scored agents · ${openFlags[0].n} open flags in the DB right now\n`));

  /* Each candidate rule, with the same population, so they are comparable. */
  const options = [
    ['CURRENT — below the function average',
     (r) => Number(r.pts) < Number(r.fn_avg),
     'fires on ~half the group by construction; cannot ever flag fewer'],
    ['Below the function average by more than half a standard deviation',
     (r) => Number(r.pts) < Number(r.fn_avg) - 0.5 * Number(r.fn_sd || 0),
     'scales with how tightly the function actually clusters'],
    ['Bottom quartile of the function',
     (r) => Number(r.pts) < Number(r.fn_p25),
     'a fixed, explainable share — "the lowest 25% of your team"'],
    ['Net Points below zero (the scorecard\'s own pass mark)',
     (r) => Number(r.pts) < 0,
     'uses the threshold the scorecard already defines, not a relative one'],
  ];

  for (const [label, fn, why] of options) {
    const k = count(fn);
    const bar = '█'.repeat(Math.round((k / n) * 40)).padEnd(40, '·');
    console.log(` ${bold(String(k).padStart(3))} / ${n}  ${pct(k).padStart(6)}  ${bar}`);
    console.log(`   ${label}`);
    console.log(dim(`   ${why}\n`));
  }

  /* Who would come OFF the list under each alternative — these are real people. */
  const cur = rows.filter((r) => Number(r.pts) < Number(r.fn_avg));
  const p25 = new Set(rows.filter((r) => Number(r.pts) < Number(r.fn_p25)).map((r) => r.employee_no));
  const wouldClear = cur.filter((r) => !p25.has(r.employee_no));
  console.log(bold(`Under "bottom quartile", ${wouldClear.length} people currently flagged would come off the list:`));
  for (const r of wouldClear.slice(0, 12))
    console.log(`   ${r.nm} ${dim(`(${r.fn})`)} — ${r.pts} pts vs function avg ${Number(r.fn_avg).toFixed(1)}`);
  if (wouldClear.length > 12) console.log(dim(`   …and ${wouldClear.length - 12} more`));

  console.log(`\n${dim('REPORT ONLY — no flag was created, changed or closed. Changing the trigger is')}`);
  console.log(`${dim('a business-rule decision (BR-APP-006); this script exists to inform it, not to make it.')}\n`);
  await c.end();
})().catch((e) => { console.error('FATAL', e.message); process.exit(1); });
